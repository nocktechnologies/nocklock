// requireSandboxExec skips the enforcement proof when sandbox-exec is
// unavailable — UNLESS NOCKLOCK_SANDBOX_REQUIRE=1, under which the skip becomes
// a HARD FAILURE. The macOS CI job (macos-enforce) sets that var so a runner
// that has lost sandbox-exec can never report green by silently skipping the
// only proof of the SBPL fence's runtime enforcement. Mirrors the netns suite's
// "a skip is not a pass" discipline (strictlyRequired).
func requireSandboxExec(t *testing.T) {
	t.Helper()
	if err := EnsureSandboxExecAvailable(); err != nil {
		if os.Getenv("NOCKLOCK_SANDBOX_REQUIRE") == "1" {
			t.Fatalf("sandbox-exec unavailable: %v; NOCKLOCK_SANDBOX_REQUIRE=1 forbids skipping", err)
		}
		t.Skipf("sandbox-exec unavailable: %v", err)
	}
}

// TestSeatbeltEnforcement_RealSandboxExec is the end-to-end proof on real macOS:
// a profile generated by GenerateProfile, run via WrapArgv + sandbox-exec, must
// actually DENY reads of a fenced directory while ALLOWING reads elsewhere. This
// is what makes the fence real rather than theoretical.
func TestSeatbeltEnforcement_RealSandboxExec(t *testing.T) {
	requireSandboxExec(t)

	base := t.TempDir()
	secretDir := filepath.Join(base, "secrets")
	allowedDir := filepath.Join(base, "project")
	if err := os.Mkdir(secretDir, 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(allowedDir, 0700); err != nil {
		t.Fatal(err)
	}
	secretFile := filepath.Join(secretDir, "id_rsa")
	allowedFile := filepath.Join(allowedDir, "ok.txt")
	if err := os.WriteFile(secretFile, []byte("SUPER-SECRET"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(allowedFile, []byte("fine"), 0600); err != nil {
		t.Fatal(err)
	}

	profile, err := GenerateProfile([]string{secretDir})
	if err != nil {
		t.Fatalf("GenerateProfile: %v", err)
	}
	pf, err := WriteProfile(profile)
	if err != nil {
		t.Fatalf("WriteProfile: %v", err)
	}
	defer os.Remove(pf)

	run := func(target string) (string, error) {
		argv, err := WrapArgv(pf, []string{"/bin/cat", target})
		if err != nil {
			t.Fatalf("WrapArgv: %v", err)
		}
		out, err := exec.Command(argv[0], argv[1:]...).CombinedOutput()
		return string(out), err
	}

	// Allowed path: should succeed and return content.
	if out, err := run(allowedFile); err != nil {
		t.Errorf("allowed file read failed under fence: err=%v out=%q", err, out)
	} else if got := string(out); got != "fine" {
		t.Errorf("allowed file content = %q, want %q", got, "fine")
	}

	// Fenced path: must be denied (non-nil error, secret not leaked).
	out, err := run(secretFile)
	if err == nil {
		t.Errorf("FENCE FAILED OPEN: secret read succeeded under fence: %q", out)
	}
	if strings.Contains(out, "SUPER-SECRET") {
		t.Errorf("FENCE LEAKED SECRET: output contained the secret: %q", out)
	}
}

// TestSeatbeltHomeReadWildcardRejectsMetadata shows why the home rule uses
// file-read-data: a file-read* variant also blocks stat outside the root.
func TestSeatbeltHomeReadWildcardRejectsMetadata(t *testing.T) {
	requireSandboxExec(t)
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		t.Fatalf("home: %v", err)
	}
	base, err := os.MkdirTemp(home, ".nocklock-read-op-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(base)
	root := filepath.Join(base, "project")
	outside := filepath.Join(base, "outside.txt")
	gitConfig := filepath.Join(base, ".gitconfig")
	if err := os.Mkdir(root, 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(outside, []byte("fixture"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(gitConfig, []byte("[core]\n"), 0600); err != nil {
		t.Fatal(err)
	}
	profile, _, err := GenerateEffectiveProfile(&FenceConfig{
		Root: root, Mode: "read-write", DenyPaths: []string{filepath.Join(base, "secret")}, HomeReadRoot: base,
	}, false, "", 0)
	if err != nil {
		t.Fatal(err)
	}
	run := func(profile string, command ...string) error {
		t.Helper()
		path, err := WriteProfile(profile)
		if err != nil {
			t.Fatal(err)
		}
		defer os.Remove(path)
		argv, err := WrapArgv(path, command)
		if err != nil {
			t.Fatal(err)
		}
		return exec.Command(argv[0], argv[1:]...).Run()
	}
	if err := run(profile, "/usr/bin/stat", "-f", "%N", outside); err != nil {
		t.Fatalf("file-read-data profile blocked metadata: %v", err)
	}
	if err := run(profile, "/bin/cat", gitConfig); err != nil {
		t.Fatalf("small Git config read exception failed: %v", err)
	}
	if err := run(profile, "/bin/cat", outside); err == nil {
		t.Fatal("file-read-data profile allowed outside data read")
	}
	wildcard := strings.ReplaceAll(profile, "file-read-data", "file-read*")
	if err := run(wildcard, "/usr/bin/stat", "-f", "%N", outside); err == nil {
		t.Fatal("file-read* variant unexpectedly allowed outside-root metadata")
	}
}

func TestSeatbeltHomeReadAllowPathsRemainReadable(t *testing.T) {
	requireSandboxExec(t)
	home, err := os.UserHomeDir()
	if err != nil {
		t.Fatal(err)
	}
	cache, err := os.UserCacheDir()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(cache, 0700); err != nil {
		t.Fatal(err)
	}
	canonicalHome, err := canonicalizeForProfile(home)
	if err != nil {
		t.Fatal(err)
	}
	canonicalCache, err := canonicalizeForProfile(cache)
	if err != nil {
		t.Fatal(err)
	}
	if !pathContains(canonicalHome, canonicalCache) {
		t.Fatalf("cache %q is outside passwd home %q; cannot prove the home-read grant", canonicalCache, canonicalHome)
	}
	for _, grantType := range []string{"allow", "allow_rw"} {
		t.Run(grantType, func(t *testing.T) {
			base, err := os.MkdirTemp(cache, ".nocklock-home-allow-")
			if err != nil {
				t.Fatal(err)
			}
			defer os.RemoveAll(base)
			root := filepath.Join(base, "project")
			allowed := filepath.Join(base, "allowed")
			secret := filepath.Join(allowed, "secret")
			for _, path := range []string{root, secret} {
				if err := os.MkdirAll(path, 0700); err != nil {
					t.Fatal(err)
				}
			}
			secretFile := filepath.Join(secret, "credential")
			if err := os.WriteFile(secretFile, []byte("sensitive"), 0600); err != nil {
				t.Fatal(err)
			}
			fc := &FenceConfig{Root: root, Mode: "read-write", DenyPaths: []string{secret}, HomeReadRoot: home}
			if grantType == "allow" {
				fc.AllowPaths = []string{allowed}
			} else {
				fc.AllowRWPaths = []string{allowed}
			}
			profile, _, err := GenerateEffectiveProfile(fc, false, "", 0)
			if err != nil {
				t.Fatal(err)
			}
			pf, err := WriteProfile(profile)
			if err != nil {
				t.Fatal(err)
			}
			defer os.Remove(pf)
			run := func(command ...string) (string, error) {
				argv, err := WrapArgv(pf, command)
				if err != nil {
					t.Fatal(err)
				}
				out, err := exec.Command(argv[0], argv[1:]...).CombinedOutput()
				return string(out), err
			}
			written := filepath.Join(allowed, "cache.txt")
			if out, err := run("/bin/sh", "-c", `printf readable > "$1" && /bin/cat "$1"`, "sh", written); err != nil || out != "readable" {
				t.Fatalf("allowed write then read = %q, %v; want readable", out, err)
			}
			if out, err := run("/bin/cat", secretFile); err == nil || strings.Contains(out, "sensitive") {
				t.Fatalf("sensitive read = %q, %v; want denial", out, err)
			}
			if out, err := run("/bin/sh", "-c", `printf changed > "$1"`, "sh", secretFile); err == nil {
				t.Fatalf("sensitive write succeeded: %q", out)
			}
			if got, err := os.ReadFile(secretFile); err != nil || string(got) != "sensitive" {
				t.Fatalf("sensitive file changed to %q: %v", got, err)
			}
		})
	}
}

